/**给你一个非负整数数组 nums ，你最初位于数组的 第一个下标 。数组中的每个元素代表你在该位置可以跳跃的最大长度。

判断你是否能够到达最后一个下标，如果可以，返回 true ；否则，返回 false 。

 

示例 1：

输入：nums = [2,3,1,1,4]
输出：true
解释：可以先跳 1 步，从下标 0 到达下标 1, 然后再从下标 1 跳 3 步到达最后一个下标。
示例 2：

输入：nums = [3,2,1,0,4]
输出：false
解释：无论怎样，总会到达下标为 3 的位置。但该下标的最大跳跃长度是 0 ， 所以永远不可能到达最后一个下标。

思路：
1. 维护能到达的最远下标 max。
2. 只有 i <= max 才能从 i 起跳，更新 max。
3. 边界：max 覆盖末尾即 true；出现 i > max 则到不了。
复杂度：时间 O(n)，空间 O(1)

——— 延伸 ———
- 从后往前：last 能被前面覆盖就前移，看最后能不能到 0。
- 最小跳跃次数：45 题，按覆盖分层。
- 有障碍格：把那格当 0，覆盖不到就失败。

——— 常见追问 ———
Q: i > max 意味着什么？
A: 前面所有能走到的格子都跳不到 i，更到不了后面。可以提前 false。本题循环里用 i <= max 挡着。

Q: 为什么可以提前返回 true？
A: max 已经盖住末尾，后面怎么跳都到得了。

Q: 全是 0？
A: n=1 时一开始就在终点。n>1 时 max 停在 0，到不了。

Q: 贪心为什么对？
A: 只关心最远可达。能到 i 就能用 nums[i] 更新最远，不必枚举跳几步。
 */

/**
 * @param {number[]} nums
 * @return {boolean}
 */
var canJump = function(nums) {
    let max = 0;
    const len = nums.length;
    for(let i = 0; i < len; i++) {
        if(max >= len - 1) return true;
        if(i <=  max) { // 到不了 i 就不能从这里起跳
            max = Math.max(i + nums[i], max);
        }
    }
    return false;
};
