/**
 * 思路：
 * 1. dp[i] = 爬到第 i 阶的方法数，最后一步只能跨 1 阶或 2 阶。
 * 2. dp[i] = dp[i-1] + dp[i-2]。dp[0]=1，dp[1]=1。
 * 3. 边界：n=1 直接返回 1。
 * 复杂度：时间 O(n)，空间 O(n)
 *
 * ——— 延伸 ———
 * - 一次可跨 1..k 阶：dp[i] += dp[i-j] for j = 1..k。
 * - 空间 O(1)：只留 a、b 两个变量，斐波那契。
 * - 带代价爬楼梯：每阶有 cost，min(dp[i-1], dp[i-2]) + cost[i]。
 * - 矩阵快速幂：O(log n) 求斐波那契。
 *
 * ——— 常见追问 ———
 * Q: dp[0] = 1 是什么意思？
 * A: 站在地面，一种「什么都不做」的方案。这样 dp[2] = dp[1] + dp[0] = 2。
 *
 * Q: 和斐波那契差在哪？
 * A: 就是斐波那契，下标偏移：F(n+1)。n = 1 返回 1，n = 2 返回 2。
 *
 * Q: 能递归吗？
 * A: 能，但要记忆化，否则指数爆炸。
 *
 * Q: 模 1e9+7？
 * A: 进阶版会要求。每次加完取模。
 *
 * @param {number} n
 * @return {number}
 */
var climbStairs = function(n) {
    const dp = [];
    dp[0] = 1; // 地面一种空方案，dp[2] 才能得到 2
    dp[1] = 1;

    for(let i = 2; i <= n; i++) {
        dp[i] = dp[i - 1] + dp[i - 2]; // 最后一步跨 1 或 2
    }
    return dp[n];
};
